def test_a_cut_never_leaves_part_of_a_word() -> None:
    assert handoff._bounded("aaa bbbbbbbb ccc", 6) == "aaa…"
    assert handoff._bounded("aaa bbbbbbbb ccc", 10, keep_end=True) == "…ccc"
    assert handoff._bounded("aaa bbbbbbbb ccc", 7, keep_end=True) == "…ccc"
    assert handoff._bounded("short", 10) == "short"


