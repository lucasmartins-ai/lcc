def test_codex_rollout_gives_patched_files_and_the_failing_command(
    stash: Path, tmp_path: Path
) -> None:
    def item(payload: dict[str, object]) -> str:
        return json.dumps({"type": "response_item", "payload": payload})

    def say(*texts: str) -> str:
        parts = [{"type": "input_text", "text": text} for text in texts]
        return item({"type": "message", "role": "user", "content": parts})

    lines = [
        json.dumps({"type": "session_meta", "payload": {"id": "x"}}),
        say("# AGENTS.md instructions for /r\n\n<INSTRUCTIONS>be nice</INSTRUCTIONS>"),
        say("<environment_context>\n  <cwd>/r</cwd>\n</environment_context>"),
        # Newer rollouts put AGENTS.md, the environment and the prompt in one message.
        say("# AGENTS.md instructions\n\nbe nice", "<environment_context/>", "first ask"),
        say("add a cache to fetch()"),
        item(
            {
                "type": "custom_tool_call",
                "call_id": "c1",
                "name": "apply_patch",
                "input": "*** Begin Patch\n*** Update File: src/fetch.py\n@@\n-a\n+b\n*** End Patch",
            }
        ),
        item({"type": "custom_tool_call_output", "call_id": "c1", "output": "Success"}),
        item(
            {
                "type": "function_call",
                "call_id": "c2",
                "name": "exec_command",
                "arguments": json.dumps({"cmd": "pytest -q"}),
            }
        ),
        item(
            {
                "type": "function_call_output",
                "call_id": "c2",
                "output": "E   AssertionError\nFAILED test_x.py::test_cache",
            }
        ),
    ]
    path = tmp_path / "rollout.jsonl"
    path.write_text("\n".join(lines), encoding="utf-8")
    packet = build(*load(path))
    assert "```\nfirst ask\n```\n\n```\nadd a cache to fetch()\n```" in packet
    assert "AGENTS.md" not in packet and "environment_context" not in packet
    assert "## Files edited\n\n- `src/fetch.py`\n" in packet
    assert (
        "Tool: `exec_command`\n\n```\nE   AssertionError\nFAILED test_x.py::test_cache\n```"
        in packet
    )


