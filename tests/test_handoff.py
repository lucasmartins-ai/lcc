def test_every_listed_stash_id_resolves_and_bad_ones_are_named(stash: Path, tmp_path: Path) -> None:
    good = put("pytest output: FAILED tests/test_api.py::test_refund_77\n" + "line\n" * 40)
    corrupt = put("some other output that will be damaged on disk\n" * 5)
    (stash / corrupt).write_bytes(b"tampered")
    pointers = [
        cc("assistant", [use("b2", "Bash", command="pytest")]),
        cc(
            "user",
            [
                result(
                    "b2",
                    f"[removed: 41 lines · lcc recall {good[:12]}]\n"
                    f"[removed: 5 lines · lcc recall {corrupt[:12]}]\n"
                    "[removed: 3 lines · lcc recall 0123456789ab]",
                )
            ],
        ),
    ]
    packet = build(*load(claude_session(tmp_path, pointers)))
    listed = [
        line.split()[3]
        for line in packet.split("## Stashed outputs")[1].split("Not recallable")[0].splitlines()
        if line.startswith("- lcc recall ")
    ]
    assert listed == [good[:12]]
    assert all(recall(stash_id).startswith("pytest output") for stash_id in listed)
    assert "· `pytest output: FAILED tests/test_api.py::test_refund_77 line line" in packet
    assert f"- {corrupt[:12]}: fails its hash check" in packet
    assert "- 0123456789ab: not in this stash" in packet


