def test_long_sessions_read_the_head_and_the_tail(
    stash: Path, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    monkeypatch.setattr(handoff, "HEAD_BYTES", 200)
    monkeypatch.setattr(handoff, "TAIL_BYTES", 400)
    filler = [cc("assistant", "thinking " * 20) for _ in range(50)]
    path = tmp_path / "long.jsonl"
    path.write_text(
        "\n".join([cc("user", "the first request"), *filler, cc("user", "the last request")]),
        encoding="utf-8",
    )
    raw, source = load(path)
    packet = build(raw, source)
    assert "the first request" in packet and "the last request" in packet
    assert source.read == "first 200 and last 400 bytes"
    assert source.size == path.stat().st_size


def test_write_is_content_addressed_private_and_ignored(tmp_path: Path) -> None:
    root = tmp_path / ".lcc" / "handoff"
    first = write("# lcc handoff\n", root)
    assert write("# lcc handoff\n", root) == first
    assert first.name.endswith(".md") and len(first.stem) == 12
    assert (root / ".gitignore").read_text() == "*\n"
    if os.name == "posix":
        assert stat.S_IMODE(first.stat().st_mode) == 0o600


def test_cli_writes_the_packet_and_prints_its_path(
    stash: Path, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    session = claude_session(tmp_path)
    monkeypatch.chdir(tmp_path)
    out = CliRunner().invoke(app, ["handoff", str(session)])
    assert out.exit_code == 0, out.output
    written = Path(out.output.strip())
    assert written.parent == Path(".lcc/handoff")
    assert "now run test_refund_77 again" in written.read_text(encoding="utf-8")
    printed = CliRunner().invoke(app, ["handoff", str(session), "--stdout"])
    assert printed.output == written.read_text(encoding="utf-8")


def test_cli_fails_cleanly_on_a_missing_or_bad_transcript(stash: Path, tmp_path: Path) -> None:
    missing = CliRunner().invoke(app, ["handoff", str(tmp_path / "nope.jsonl")])
    assert missing.exit_code == 2
    bad = tmp_path / "bad.json"
    bad.write_text(json.dumps({"messages": [{"text": "no role"}]}), encoding="utf-8")
    assert CliRunner().invoke(app, ["handoff", str(bad)]).exit_code == 2


def test_cli_fails_cleanly_on_an_unwritable_out(stash: Path, tmp_path: Path) -> None:
    blocker = tmp_path / "a-file"
    blocker.write_text("", encoding="utf-8")
    out = CliRunner().invoke(app, ["handoff", str(claude_session(tmp_path)), "--out", str(blocker)])
    assert out.exit_code == 2
    assert not isinstance(out.exception, OSError)


