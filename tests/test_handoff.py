def test_secrets_are_masked_and_long_names_without_digits_survive() -> None:
    assert mask("token ghp_abcdefghijklmnopqrstuvwx here") == "token <TOKEN> here"
    assert mask("Authorization: Bearer abc.def") == "<TOKEN>"
    name = "test_redaction_of_long_inputs_finishes_under_one_second"
    assert mask(f"FAILED {name}") == f"FAILED {name}"
    assert mask("key 3f9a1c0d8e7b6a5f4e3d2c1b0a9f8e7d6c5b4a39") == "key <TOKEN>"


def test_a_cut_never_leaves_part_of_a_word() -> None:
    assert handoff._bounded("aaa bbbbbbbb ccc", 6) == "aaa…"
    assert handoff._bounded("aaa bbbbbbbb ccc", 10, keep_end=True) == "…ccc"
    assert handoff._bounded("aaa bbbbbbbb ccc", 7, keep_end=True) == "…ccc"
    assert handoff._bounded("short", 10) == "short"


