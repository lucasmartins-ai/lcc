def cc(role: str, content: object, **extra: object) -> str:
    """One Claude Code JSONL record."""
    return json.dumps({"type": role, "message": {"role": role, "content": content}, **extra})


def use(call_id: str, name: str, **tool_input: object) -> dict[str, object]:
    return {"type": "tool_use", "id": call_id, "name": name, "input": tool_input}


def result(call_id: str, text: str, *, error: bool = False) -> dict[str, object]:
    return {"type": "tool_result", "tool_use_id": call_id, "content": text, "is_error": error}


def claude_session(tmp_path: Path, extra: list[str] | None = None) -> Path:
    lines = [
        cc("user", "Fix the refund bug in src/api.py"),
        cc("assistant", [use("r1", "Read", file_path="/r/src/api.py")]),
        cc("user", [result("r1", "def refund():\n    return None")]),
        cc("assistant", [use("e1", "Edit", file_path="/r/src/api.py")]),
        cc("user", [result("e1", "ok")]),
        cc("assistant", [use("b1", "Bash", command="pytest -q")]),
        cc(
            "user",
            [
                result(
                    "b1",
                    "FAILED tests/test_api.py::test_refund_77\n"
                    "API_KEY=sk-live-abcdefghijklmnop12345 in env",
                    error=True,
                )
            ],
        ),
        cc("user", "<system-reminder>not a prompt</system-reminder>"),
        cc("user", "Caveat: the messages below were generated by the user", isMeta=True),
        cc("user", "This session is being continued from a previous one", isCompactSummary=True),
        cc("user", "now run test_refund_77 again"),
        *(extra or []),
    ]
    path = tmp_path / "session.jsonl"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


SOURCE = Source(path="/s/session.jsonl", size=10, sha256="ab" * 32, read="whole file")


