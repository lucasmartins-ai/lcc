def test_a_message_sent_mid_turn_is_the_latest_request(stash: Path, tmp_path: Path) -> None:
    def queued(prompt: str, kind: str) -> str:
        attachment = {"type": "queued_command", "prompt": prompt, "origin": {"kind": kind}}
        return json.dumps({"type": "attachment", "attachment": attachment})

    extra = [queued("also update the docs", "human"), queued("from a bot", "task")]
    packet = build(*load(claude_session(tmp_path, extra)))
    requests = packet.split("## Files edited")[0]
    assert requests.endswith("```\nalso update the docs\n```\n\n")
    assert "from a bot" not in packet
