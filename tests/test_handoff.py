def test_corrupt_blobs_spend_the_byte_budget(
    stash: Path, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    first, second = put("a" * 600), put("b" * 600)
    (stash / first).write_bytes(b"c" * 600)
    monkeypatch.setattr(handoff, "MAX_BLOB_BYTES", 1000)
